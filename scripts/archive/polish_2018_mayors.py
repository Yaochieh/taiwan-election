def main():
    conn = sqlite3.connect(DB)
    cur = conn.cursor()
    n = 0
    for name, content in POLISHED.items():
        ids = cur.execute(
            "SELECT candidate_id FROM candidates WHERE election_id=42 AND name=?",
            (name,),
        ).fetchall()
        if not ids:
            print(f"  ? {name}")
            continue
        cid = ids[0][0]
        # 已有 platforms 就略過（保留 OCR）
        ex = cur.execute(
            "SELECT COUNT(*) FROM platforms WHERE candidate_id=? AND election_id=42",
            (cid,),
        ).fetchone()[0]
        if ex > 0:
            print(f"  - {name}: 已有 {ex} 條，跳過")
            continue
        cur.execute(
            "INSERT INTO platforms (candidate_id, election_id, seq, content, note) VALUES (?, 42, 1, ?, ?)",
            (cid, content, TAG),
        )
        n += 1
        print(f"  ✓ {name}")
    conn.commit()
    print(f"\n✓ 2018 縣市長補完 {n} 位")
    conn.close()


if __name__ == "__main__":
    main()
