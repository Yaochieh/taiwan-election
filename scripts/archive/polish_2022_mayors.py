def main():
    conn = sqlite3.connect(DB)
    cur = conn.cursor()
    n = 0
    for name, content in POLISHED.items():
        ids = cur.execute(
            "SELECT candidate_id FROM candidates WHERE election_id=49 AND name=?",
            (name,),
        ).fetchall()
        if not ids:
            print(f"  ? {name}")
            continue
        cid = ids[0][0]
        cur.execute("DELETE FROM platforms WHERE candidate_id=? AND election_id=49", (cid,))
        cur.execute(
            "INSERT INTO platforms (candidate_id, election_id, seq, content, note) VALUES (?, 49, 1, ?, ?)",
            (cid, content, TAG),
        )
        n += 1
        print(f"  ✓ {name}")
    conn.commit()
    print(f"\n✓ 共 {n} 位 2022 縣市長")
    conn.close()


if __name__ == "__main__":
    main()
