def main():
    conn = sqlite3.connect(DB)
    cur = conn.cursor()
    updated = 0
    for name, p in POLISHED.items():
        n = cur.execute(
            """UPDATE platforms
               SET content=?, note=?
               WHERE candidate_id IN (
                   SELECT c.candidate_id FROM candidates c
                   JOIN elections e ON c.election_id=e.election_id
                   WHERE e.date='2024-01-13' AND e.type='presidential' AND c.name=?
               )""",
            (p["content"], p["note"], name),
        ).rowcount
        updated += n
        print(f"  {name}: {n} row")
    conn.commit()
    print(f"\n✓ 共潤稿 {updated} 條")
    conn.close()


if __name__ == "__main__":
    main()
