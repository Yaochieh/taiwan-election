def main():
    conn = sqlite3.connect(DB)
    cur = conn.cursor()
    n_total = 0
    for name, content in POLISHED.items():
        # 刪除該候選人在 election=51 的所有舊 platforms
        ids = cur.execute(
            "SELECT candidate_id FROM candidates WHERE election_id=51 AND name=?",
            (name,),
        ).fetchall()
        if not ids:
            print(f"  ? {name}: 找不到候選人")
            continue
        cand_id = ids[0][0]
        cur.execute("DELETE FROM platforms WHERE candidate_id=? AND election_id=51", (cand_id,))
        cur.execute(
            """INSERT INTO platforms (candidate_id, election_id, seq, content, note)
               VALUES (?, ?, 1, ?, ?)""",
            (cand_id, 51, content, TAG),
        )
        n_total += 1
        print(f"  ✓ {name}")
    conn.commit()
    print(f"\n共 {n_total} 位立委政見潤稿")
    conn.close()


if __name__ == "__main__":
    main()
