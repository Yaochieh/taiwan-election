def main():
    conn = sqlite3.connect(DB)
    cur = conn.cursor()
    n = 0
    for date_str, name, content in POLISHED:
        ids = cur.execute(
            """SELECT c.candidate_id FROM candidates c
               JOIN elections e ON c.election_id=e.election_id
               WHERE e.date=? AND e.type='presidential' AND c.name=?""",
            (date_str, name),
        ).fetchall()
        if not ids:
            print(f"  ? {date_str} {name}")
            continue
        cid = ids[0][0]
        cur.execute("DELETE FROM platforms WHERE candidate_id=?", (cid,))
        eid = cur.execute("SELECT election_id FROM candidates WHERE candidate_id=?", (cid,)).fetchone()[0]
        cur.execute(
            "INSERT INTO platforms (candidate_id, election_id, seq, content, note) VALUES (?, ?, 1, ?, ?)",
            (cid, eid, content, TAG),
        )
        n += 1
        print(f"  ✓ {date_str} {name}")
    conn.commit()
    print(f"\n✓ 共 {n} 位歷屆總統候選人")
    conn.close()


if __name__ == "__main__":
    main()
