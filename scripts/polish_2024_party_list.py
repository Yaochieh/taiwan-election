def main():
    conn = sqlite3.connect(DB)
    cur = conn.cursor()
    updated = 0
    for name, content in POLISHED.items():
        n = cur.execute(
            """UPDATE platforms
               SET content=?, note=?
               WHERE candidate_id IN (
                   SELECT c.candidate_id FROM candidates c
                   WHERE c.election_id=50 AND c.name=?
               )""",
            (content, TAG, name),
        ).rowcount
        updated += n
        if n:
            print(f"  ✓ {name}")
        else:
            print(f"  ? {name} (找不到)")
    conn.commit()
    print(f"\n共 {updated} 條政見潤稿")
    conn.close()


if __name__ == "__main__":
    main()
