def main():
    conn = sqlite3.connect(DB)
    cur = conn.cursor()
    n_total = 0
    for name, content in POLISHED.items():
        # 不分區 (election=50) 或 區域 (election=51)
        ids = cur.execute(
            "SELECT candidate_id, election_id FROM candidates "
            "WHERE election_id IN (50,51) AND name=?",
            (name,),
        ).fetchall()
        if not ids:
            print(f"  ? {name}: 找不到")
            continue
        for cid, eid in ids:
            cur.execute("DELETE FROM platforms WHERE candidate_id=?", (cid,))
            cur.execute(
                """INSERT INTO platforms (candidate_id, election_id, seq, content, note)
                   VALUES (?, ?, 1, ?, ?)""",
                (cid, eid, content, TAG),
            )
        n_total += 1
        print(f"  ✓ {name}")
    conn.commit()
    print(f"\n共 {n_total} 位立委")
    conn.close()


if __name__ == "__main__":
    main()
