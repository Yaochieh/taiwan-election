def main():
    conn = sqlite3.connect(DB)
    cur = conn.cursor()
    n_total = 0
    for name, content in POLISHED.items():
        ids = cur.execute(
            "SELECT candidate_id FROM candidates WHERE election_id=51 AND name=?",
            (name,),
        ).fetchall()
        if not ids:
            print(f"  ? {name}")
            continue
        cid = ids[0][0]
        # 保留原始 content 進 content_raw（如果還沒）
        original = cur.execute(
            "SELECT content, content_raw FROM platforms WHERE candidate_id=? AND election_id=51 LIMIT 1",
            (cid,),
        ).fetchone()
        raw = original[1] if original and original[1] else (original[0] if original else None)
        cur.execute("DELETE FROM platforms WHERE candidate_id=? AND election_id=51", (cid,))
        cur.execute(
            """INSERT INTO platforms
               (candidate_id, election_id, seq, content, content_raw, note)
               VALUES (?, 51, 1, ?, ?, ?)""",
            (cid, content, raw, TAG),
        )
        n_total += 1
        print(f"  ✓ {name}")
    conn.commit()
    print(f"\n共 {n_total} 位立委")
    conn.close()


if __name__ == "__main__":
    main()
